// ─── أدوات مساعدة ───
export function getSubject(id: string): Subject | undefined {
  return SUBJECTS.find((s) => s.id === id);
}

export function totalLessons(subject: Subject): number {
  return subject.units.reduce((s, u) => s + u.lessons.length, 0);
}

export function totalAllLessons(): number {
  return SUBJECTS.reduce((s, sub) => s + totalLessons(sub), 0);
}
